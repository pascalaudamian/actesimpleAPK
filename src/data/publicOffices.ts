/**
 * Filter offices relevant to a specific procedure
 */
export function getOfficesForProcedure(
  procedureId: string,
  procedureCategory: string,
  selectedCity?: string
): PublicOffice[] {
  let list = ROMANIAN_PUBLIC_OFFICES.filter((office) => {
    // 1. Direct procedure ID match
    if (office.procedureIds && office.procedureIds.includes(procedureId)) {
      return true;
    }
    // 2. Category matching
    if (office.categories.includes(procedureCategory)) {
      return true;
    }
    return false;
  });

  // If no direct matches, fallback to generic offices matching the category
  if (list.length === 0) {
    list = ROMANIAN_PUBLIC_OFFICES.filter((office) =>
      office.categories.includes(procedureCategory)
    );
  }

  // City filter
  if (selectedCity && selectedCity !== 'toate') {
    list = list.filter((office) => office.city === selectedCity);
  }

  return list;
}
